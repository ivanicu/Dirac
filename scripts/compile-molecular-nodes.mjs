#!/usr/bin/env node

import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, renameSync, unlinkSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, relative, resolve } from 'node:path';
import process from 'node:process';
import { compileMolecularNodesGraph, stableStringify } from './lib/mn-graph-compiler.mjs';

const repoRoot = resolve(import.meta.dirname, '..');

function usage() {
    console.log(`Molecular Representation AOT Compiler

Usage:
  node scripts/compile-molecular-nodes.mjs --graph graph.json [options]
  node scripts/compile-molecular-nodes.mjs --blend node_data_file.blend --blender /path/to/blender [options]

Options:
  --output FILE       Compiled bundle (default: src/mol-plugin-chem/visual-r4/compiled/mn-r4.bundle.json)
  --manifest FILE     TypeScript manifest (default: beside the bundle)
  --check             Compile twice and require byte-identical output
  --help              Show this help
`);
}

function parseArgs(argv) {
    const options = { check: false };
    for (let i = 0; i < argv.length; i++) {
        const arg = argv[i];
        if (arg === '--check') options.check = true;
        else if (arg === '--help') options.help = true;
        else if (arg.startsWith('--')) {
            const key = arg.slice(2);
            const value = argv[++i];
            if (!value || value.startsWith('--')) throw new Error(`missing value for ${arg}`);
            options[key] = value;
        } else throw new Error(`unexpected argument: ${arg}`);
    }
    return options;
}

function extractBlend(options) {
    if (!options.blender) throw new Error('--blender is required with --blend');
    const graphPath = resolve('/tmp', `molecular-nodes-graph-${process.pid}.json`);
    const result = spawnSync(resolve(options.blender), [
        '--background',
        '--python', resolve(repoRoot, 'scripts/dump-molecular-nodes-graph.py'),
        '--', resolve(options.blend), graphPath,
    ], { encoding: 'utf8', timeout: 180_000, maxBuffer: 16 * 1024 * 1024 });
    if (!existsSync(graphPath)) {
        const detail = result.stderr || result.stdout || result.error?.message || `exit ${result.status}`;
        throw new Error(`Blender graph extraction failed: ${detail.trim()}`);
    }
    if (result.status !== 0 && !result.error) {
        console.warn(`Blender exited ${result.status} after producing the graph; accepting the complete artifact.`);
    }
    return { graphPath, temporary: true };
}

function manifestSource(bundle, bundlePath) {
    const manifest = {
        schema: bundle.schema,
        bundleFile: basename(bundlePath),
        artifact: bundle.artifact,
        source: bundle.source,
        programs: bundle.programs,
        stats: bundle.stats,
        runtime: bundle.runtime,
    };
    return `/* eslint-disable quotes */\n// Generated by scripts/compile-molecular-nodes.mjs. Do not hand-edit.\n` +
        `export const MolecularNodesCompiledManifest = Object.freeze(${stableStringify(manifest, 4)} as const);\n`;
}

function sha256(value) {
    return createHash('sha256').update(value).digest('hex');
}

function compilerOptions(rawText, options) {
    const kernelSources = ['kernels/curve-extrude.wgsl'];
    const kernelHashes = Object.fromEntries(kernelSources.map(source => {
        const path = resolve(repoRoot, 'src/mol-plugin-chem/visual-r4/compiled', source);
        return [source, sha256(readFileSync(path))];
    }));
    return {
        asset: options.asset ?? 'molecularnodes/assets/node_data_file.blend',
        upstreamRepository: options['upstream-repository'],
        upstreamCommit: options['upstream-commit'],
        upstreamVersion: options['upstream-version'],
        graphHash: sha256(rawText),
        kernelHashes,
    };
}

function compile(raw, rawText, options) {
    return compileMolecularNodesGraph(raw, {
        ...compilerOptions(rawText, options),
    });
}

function main() {
    const options = parseArgs(process.argv.slice(2));
    if (options.help) {
        usage();
        return;
    }
    if (Boolean(options.graph) === Boolean(options.blend)) throw new Error('provide exactly one of --graph or --blend');

    const extracted = options.graph ? { graphPath: resolve(options.graph), temporary: false } : extractBlend(options);
    const outputPath = resolve(options.output ?? join(repoRoot, 'src/mol-plugin-chem/visual-r4/compiled/mn-r4.bundle.json'));
    const manifestPath = resolve(options.manifest ?? join(dirname(outputPath), 'mn-r4.manifest.ts'));
    try {
        const rawText = readFileSync(extracted.graphPath, 'utf8');
        const raw = JSON.parse(rawText);
        const bundle = compile(raw, rawText, options);
        const output = `${stableStringify(bundle)}\n`;
        if (options.check) {
            const second = `${stableStringify(compile(JSON.parse(rawText), rawText, options))}\n`;
            if (second !== output) throw new Error('determinism check failed: two compiler passes differ');
        }
        if (bundle.programs.length !== 10) throw new Error(`expected 10 public programs, compiled ${bundle.programs.length}`);
        if (bundle.diagnostics.dependencyCycles.length > 0) {
            throw new Error(`node-group dependency cycles: ${JSON.stringify(bundle.diagnostics.dependencyCycles)}`);
        }
        mkdirSync(dirname(outputPath), { recursive: true });
        mkdirSync(dirname(manifestPath), { recursive: true });
        const outputTemporary = `${outputPath}.${process.pid}.tmp`;
        const manifestTemporary = `${manifestPath}.${process.pid}.tmp`;
        writeFileSync(outputTemporary, output);
        writeFileSync(manifestTemporary, manifestSource(bundle, outputPath));
        renameSync(outputTemporary, outputPath);
        renameSync(manifestTemporary, manifestPath);
        const outputBytes = Buffer.byteLength(output);
        const report = {
            output: relative(repoRoot, outputPath),
            manifest: relative(repoRoot, manifestPath),
            rawBytes: Buffer.byteLength(rawText),
            compiledBytes: outputBytes,
            reductionPercent: Number((100 * (1 - outputBytes / Buffer.byteLength(rawText))).toFixed(1)),
            deterministic: options.check,
            hash: bundle.artifact.hash,
            ...bundle.stats,
        };
        console.log(stableStringify(report, 2));
    } finally {
        if (extracted.temporary && existsSync(extracted.graphPath)) unlinkSync(extracted.graphPath);
    }
}

try {
    main();
} catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
}
